import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import authRoutes from "./routes/auth";
import productRoutes from "./routes/products";
import dashboardRoutes from "./routes/dashboard";
import settingsRoutes from "./routes/settings";
export const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.FRONTEND_URL ? process.env.FRONTEND_URL.split(",") : "http://localhost:5173" }));
app.use(express.json({ limit: "1mb" }));
app.get("/api/health", (_req,res) => res.json({ status: "ok", service: "stockflow-api" }));
app.use("/api/auth",rateLimit({ windowMs: 900000, limit: 30, standardHeaders: true, legacyHeaders: false }),authRoutes);
app.use("/api/products",productRoutes);
app.use("/api/dashboard",dashboardRoutes);
app.use("/api/settings",settingsRoutes);
app.use((err: any,_req: express.Request,res: express.Response,_next: express.NextFunction) => {
  console.error(err);
  res.status(500).json({ message: "Internal server error" });
});
